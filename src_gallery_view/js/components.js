/**
 * @param {Tab[]} tabs 
 * @param {number} active_index
 * @returns {Node}
 */
const Tabs = (
    tabs,
    active_index = 0
) => {
    const id = `tab${Math.random()}`.replace('.','')
    return $.div(
        {class: 'tabs_object', 'id': id},
        ...tabs.map((e, i) => $.span(
            {
                class: `tab_object ${i == active_index ? ' active' : ''}`,
                onclick: () => {
                    if (selectAll('#'+id + '>span')[i].element.classList.contains('active')) return
                    selectAll('#'+id + '>span').map(e => e.classes('tab_object'))
                    selectAll('#'+id + '>span')[i].classes('tab_object', 'active')
                    e.onclick()
                }
            },
            e.name
        ))
    )
}

